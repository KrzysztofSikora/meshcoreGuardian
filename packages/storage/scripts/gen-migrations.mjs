// Turns migrations/NNNN_name.sql into src/migrations/generated.ts, so Metro and Vitest need no
// .sql loader. `--stdout` prints the module instead of writing it (used by the staleness test).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

export function renderMigrations() {
  const files = readdirSync(join(root, "migrations"))
    .filter((f) => f.endsWith(".sql"))
    .sort();
  const entries = files.map((file, i) => {
    const match = /^(\d{4})_([a-z0-9_]+)\.sql$/.exec(file);
    if (!match || Number(match[1]) !== i + 1) {
      throw new Error(`Migration ${file} must be named NNNN_name.sql and numbered without gaps.`);
    }
    const sql = readFileSync(join(root, "migrations", file), "utf8");
    return `  { version: ${i + 1}, name: ${JSON.stringify(match[2])}, sql: ${JSON.stringify(sql)} },`;
  });
  return [
    "// Generated by scripts/gen-migrations.mjs from migrations/*.sql. Do not edit.",
    "export type Migration = { readonly version: number; readonly name: string; readonly sql: string };",
    "",
    "export const MIGRATIONS: readonly Migration[] = [",
    ...entries,
    "];",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = renderMigrations();
  if (process.argv.includes("--stdout")) process.stdout.write(out);
  else writeFileSync(join(root, "src", "migrations", "generated.ts"), out);
}
